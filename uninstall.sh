#!/bin/bash

# =========================================================
# 流量监控 卸载脚本
# =========================================================

set -e

echo "================================================="
echo "流量监控 卸载"
echo "================================================="
echo

# =========================================================
# 自动识别主网卡
# =========================================================

INTERFACE=$(ip route get 1.1.1.1 | awk '{print $5; exit}')

echo "检测到主网卡：$INTERFACE"
echo

# =========================================================
# 删除 cron 定时任务
# =========================================================

echo ">>> 删除定时任务..."

crontab -l 2>/dev/null | grep -v check_bandwidth.sh | crontab -

# =========================================================
# 删除 tc 限速
# =========================================================

echo ">>> 清除限速规则..."

tc qdisc del dev $INTERFACE root 2>/dev/null || true

# =========================================================
# 删除脚本
# =========================================================

echo ">>> 删除监控脚本..."

rm -f /usr/local/bin/check_bandwidth.sh

# =========================================================
# 删除状态文件
# =========================================================

echo ">>> 删除状态文件..."

rm -rf /var/lib/bandwidth_monitor

# =========================================================
# 删除日志
# =========================================================

echo ">>> 删除日志文件..."

rm -f /var/log/bandwidth_check.log

# =========================================================
# 删除 msmtp 配置
# =========================================================

echo ">>> 删除 msmtp 配置..."

rm -f ~/.msmtprc

# =========================================================
# 完成
# =========================================================

echo
echo "================================================="
echo " 卸载完成"
echo "================================================="
echo
echo "已清除："
echo "  - 定时任务"
echo "  - tc 限速规则"
echo "  - 流量监控脚本"
echo "  - 状态文件"
echo "  - 日志文件"
echo "  - msmtp 配置"
echo
echo "系统依赖未卸载："
echo "  - msmtp"
echo "  - mailutils"
echo "  - iproute2"
echo
echo "================================================="